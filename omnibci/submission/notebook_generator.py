SFREQ = 250.0  # Hz

def butter_bandpass_filter(data, lowcut=8.0, highcut=30.0, fs=250.0, order=4):
    nyq = 0.5 * fs
    b, a = signal.butter(order, [lowcut / nyq, highcut / nyq], btype='band')
